#pragma once

#include <QString>

// ─────────────────────────────────────────────────────────────────────────────
// Качество показания датчика (REQ-019, 076, 079, 081).
//
// Отдельный заголовок намеренно: enum нужен и слою данных (DataCollection), и
// рецепту режима (VacuumTaskTree, который не должен зависеть от железа).
// Здесь нет ничего, кроме enum и его имени, — включать безопасно откуда угодно.
//
// Зачем это вообще: без признака качества рецепт не отличает валидное
// показание от последнего известного. Это не теоретическая придирка —
// VacuumController после трёх неразобранных кадров вызывал shuttingOff() →
// stopReading(), который обнулял m_lastData, а 0 Па ≤ любого порога, поэтому
// предикат удержания выполнялся и МЁРТВЫЙ ДАТЧИК ЧИТАЛСЯ КАК ДОСТИГНУТЫЙ
// ВАКУУМ.
//
// Over range — ожидание, а не отказ: в начале откачки давление заведомо выше
// верхней границы измерения (REQ-079/081 описывают именно ожидание с повторной
// проверкой). Поэтому у него отдельное значение, а не просто «невалидно».
// ─────────────────────────────────────────────────────────────────────────────

enum class Quality {
    Valid,        // показание достоверно
    OverRange,    // выше верхней границы измерения — нормальная фаза откачки
    UnderRange,   // ниже нижней границы измерения
    Stale,        // связь есть, но свежего кадра нет
    NoResponse    // датчик не отвечает / порт закрыт / разбор кадра провален
};

inline QString qualityName(Quality q)
{
    switch (q) {
    case Quality::Valid:      return QStringLiteral("валидно");
    case Quality::OverRange:  return QStringLiteral("выше диапазона");
    case Quality::UnderRange: return QStringLiteral("ниже диапазона");
    case Quality::Stale:      return QStringLiteral("устарело");
    case Quality::NoResponse: return QStringLiteral("нет ответа");
    }
    return QStringLiteral("неизвестно");
}
